import { ApiProperty } from '@nestjs/swagger';

export class MonthlyRevenueDto {
  @ApiProperty({
    description: 'Month in YYYY-MM format',
    example: '2024-01',
  })
  month: string;

  @ApiProperty({
    description: 'Total revenue for the month',
    example: 15750.5,
  })
  revenue: number;

  @ApiProperty({
    description: 'Total number of orders for the month',
    example: 45,
  })
  orderCount: number;
}

export class CategorySalesDto {
  @ApiProperty({
    description: 'Product category name',
    example: 'CHAIRS',
  })
  category: string;

  @ApiProperty({
    description: 'Total revenue from this category',
    example: 8500.75,
  })
  totalRevenue: number;

  @ApiProperty({
    description: 'Number of orders in this category',
    example: 25,
  })
  orderCount: number;
}

export class TopProductDto {
  @ApiProperty({
    description: 'Product ID',
    example: 123,
  })
  id: number;

  @ApiProperty({
    description: 'Product title',
    example: 'Luxury Office Chair',
  })
  title: string;

  @ApiProperty({
    description: 'Product category',
    example: 'CHAIRS',
  })
  category: string;

  @ApiProperty({
    description: 'Total revenue generated by this product',
    example: 2999.95,
  })
  totalRevenue: number;

  @ApiProperty({
    description: 'Number of orders for this product',
    example: 10,
  })
  orderCount: number;

  @ApiProperty({
    description: 'Average price per order',
    example: 299.99,
  })
  averagePrice: number;
}

export class TopCustomerDto {
  @ApiProperty({
    description: 'Customer user ID',
    example: 456,
  })
  id: number;

  @ApiProperty({
    description: 'Customer full name',
    example: 'John Doe',
  })
  name: string;

  @ApiProperty({
    description: 'Customer email address',
    example: 'john.doe@example.com',
  })
  email: string;

  @ApiProperty({
    description: 'Total number of orders placed',
    example: 8,
  })
  totalOrders: number;

  @ApiProperty({
    description: 'Total amount spent by customer',
    example: 2400.5,
  })
  totalSpent: number;

  @ApiProperty({
    description: 'Average order value',
    example: 300.06,
  })
  averageOrderValue: number;
}

export class AdminAnalyticsDataDto {
  @ApiProperty({
    description: 'Total revenue across all completed orders',
    example: 125750.75,
  })
  totalRevenue: number;

  @ApiProperty({
    description: 'Total number of orders in the system',
    example: 450,
  })
  totalOrders: number;

  @ApiProperty({
    description: 'Total number of registered users',
    example: 1250,
  })
  totalUsers: number;

  @ApiProperty({
    description: 'Monthly revenue and order data for the last 12 months',
    type: [MonthlyRevenueDto],
  })
  monthlyData: MonthlyRevenueDto[];

  @ApiProperty({
    description: 'Sales breakdown by product category',
    type: [CategorySalesDto],
  })
  salesByCategory: CategorySalesDto[];

  @ApiProperty({
    description: 'Top selling products by revenue',
    type: [TopProductDto],
  })
  topProducts: TopProductDto[];

  @ApiProperty({
    description: 'Top customers by order count and spending',
    type: [TopCustomerDto],
  })
  topCustomers: TopCustomerDto[];
}

export class AdminAnalyticsResponseDto {
  @ApiProperty({
    description: 'Indicates if the request was successful',
    example: true,
  })
  success: boolean;

  @ApiProperty({
    description: 'Admin analytics data',
    type: AdminAnalyticsDataDto,
  })
  data: AdminAnalyticsDataDto;
}
